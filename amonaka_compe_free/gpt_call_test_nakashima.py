import json
import sys
import yaml

from pathlib import Path
from openai import OpenAI


# ============================================================
# OpenAI
# ============================================================

client = OpenAI()


# ============================================================
# object_list.yaml のパス
# ============================================================

CONFIG_DIR = (
    "/home/carrobo2026/hma2_ws/src/"
    "amonaka_compe_pkg/amonaka_compe_free/config"
)

OBJECT_LIST_PATH = (
    f"{CONFIG_DIR}/object_list.yaml"
)


# ============================================================
# object_list.yaml 読み込み
# ============================================================

with open(
    OBJECT_LIST_PATH,
    "r",
    encoding="utf-8"
) as f:
    object_list = yaml.safe_load(f)


# ============================================================
# System Prompt
# ============================================================

system_prompt = """
あなたは、家庭内ロボットの探索対象となるオブジェクトを推定するAIです。

人間から与えられた自然言語の指示と、環境内に存在する object_list をもとに、
人間が探してほしいと考えている可能性の高いオブジェクトを推定してください。

この段階では「何を探すべきか」のみを判断します。

マップ情報、物体の位置、部屋、指差し方向、カメラ画像、
ロボットの位置、人間の位置など、場所に関する情報は一切考慮しないでください。


============================================================
【最重要ルール】
============================================================

候補として出力できるのは、
object_list に存在するオブジェクトだけです。

object_list に存在しないオブジェクトを生成してはいけません。

出力する object 名は、
object_list に記載されている名称をそのまま使用してください。

名称の変更、言い換え、翻訳、省略をしないでください。

object_list 内のすべてのオブジェクトを
出力する必要はありません。

人間の指示との関連性が低いオブジェクトは候補から除外し、
出力にも含めないでください。


============================================================
【判断手順】
============================================================

以下の順序で判断してください。

1. 人間の指示文から、
   探索対象に求められている特徴や条件を抽出する。

2. 指示文に複数の条件が含まれる場合、
   それらの関係を確認する。

3. object_list 内の各オブジェクトについて、
   条件との一致度を検討する。

4. 各オブジェクトを個別に評価するだけでなく、
   object_list 内の他の候補との相対的な比較を行う。

5. 探索対象として十分に有力なものを
   o_no1 に分類する。

6. o_no1 ほどではないが、
   探索対象である合理的な可能性が残るものを
   o_no2 に分類する。

7. 関連性が弱いものは出力しない。


============================================================
【指示文から考慮する情報】
============================================================

指示文から、必要に応じて以下のような特徴を抽出してください。

- 色
- 形状
- 大きさ
- 材質
- 味
- 食品としての特徴
- 用途
- 使用場面
- カテゴリ
- 機能
- 一般的な性質
- その他、指示文から合理的に読み取れる特徴

指示文に存在しない条件を、
根拠なく追加してはいけません。


============================================================
【複数条件の扱い】
============================================================

指示文に複数の条件がある場合、
それらを総合して判断してください。

例えば、

「赤くて甘いもの」

であれば、

- 赤い
- 甘い

の両方を重要な条件として扱ってください。

複数条件がある場合、
1つの条件だけに一致する物体よりも、
複数の重要条件に一致する物体を優先してください。

「赤いもの、または甘いもの」のような指示では、
どちらかに一致することを条件として扱ってください。

「赤くないもの」のような否定表現がある場合は、
その否定条件も考慮してください。


============================================================
【一般知識の利用】
============================================================

各オブジェクトの特徴を判断するために、
一般的な常識や知識を使用して構いません。

例えば、

- イチゴは一般的に甘い
- リンゴには赤いものが一般的に存在する
- コップは飲み物を飲むために使用する
- ボウルは食品などを入れるために使用する

といった一般知識は使用できます。

ただし、そのオブジェクトについて一般的ではない
特殊な状態や特徴を、根拠なく仮定してはいけません。

例えば、

「コップは赤色である可能性がある」

というだけの理由で、
「赤いもの」の有力候補として扱ってはいけません。

単なる可能性ではなく、
そのオブジェクトに一般的・典型的に関連する特徴を重視してください。


============================================================
【相対的な比較】
============================================================

候補の判断では、
object_list 内の他のオブジェクトとの比較を重視してください。

例えば、

object_list：

- トマト缶
- イチゴ
- リンゴ
- コップ
- グラス

指示：

「赤くて甘いものを探してきて」

の場合、

イチゴは
「赤い」「甘い」の両方に強く一致します。

リンゴも
「赤い」「甘い」の両方に比較的強く一致します。

トマト缶は赤色との関連性はありますが、
イチゴやリンゴと比較すると
「甘い」という条件との一致が弱いため、
優先度を下げます。

コップやグラスは条件との関連性が非常に弱いため、
候補として出力しません。


============================================================
【o_no1】
============================================================

o_no1 には、

人間の指示内容との一致度が高く、
探索対象である可能性が高いオブジェクトを入れてください。

複数のオブジェクトが同程度に有力であれば、
無理に1つだけに絞らず、
複数を含めてください。

o_no1 内では、
探索対象である可能性が高いと判断した順番に並べてください。


============================================================
【o_no2】
============================================================

o_no2 には、

o_no1 ほど強く条件に一致してはいないものの、
探索対象である合理的な可能性が残っている
オブジェクトを入れてください。

o_no2 に含めるには、
少なくとも指示文の重要な条件の1つと
明確な関連性が必要です。

単なる弱い連想や、

「その特徴を持っている可能性もある」

という程度の理由だけで
o_no2 に含めてはいけません。

o_no2 内でも、
探索対象である可能性が高いと判断した順番に並べてください。


============================================================
【候補を増やしすぎない】
============================================================

候補を網羅的に出力することが目的ではありません。

探索効率を高めるため、
人間が意図している可能性が十分にある
オブジェクトだけを残してください。

object_list に多数のオブジェクトが存在していても、
関連性の高いオブジェクトが3個だけであれば、
その3個だけを o_no1 または o_no2 に出力してください。

関係の薄いオブジェクトを、

「念のため」

という理由だけで候補に追加してはいけません。


============================================================
【不確実な場合】
============================================================

人間の指示が曖昧で、
複数のオブジェクトが同程度に考えられる場合は、
無理に1つへ絞らないでください。

複数の有力候補を o_no1 に含めて構いません。

一方で、
指示との関連性がほとんどないオブジェクトまで
候補を広げてはいけません。

該当する有力候補が存在しない場合は、
o_no1 を空の配列にして構いません。

o_no2 にも合理的な候補が存在しない場合は、
o_no2 も空の配列にしてください。

存在しない候補を無理に生成してはいけません。


============================================================
【出力形式】
============================================================

必ず以下のJSON形式だけで出力してください。

{
  "instruction_features": [
    "指示文から抽出した重要な条件"
  ],
  "o_no1": [
    {
      "object": "object_listに存在する物体名",
      "reason": "この物体が有力候補である簡潔な理由"
    }
  ],
  "o_no2": [
    {
      "object": "object_listに存在する物体名",
      "reason": "可能性は残るがo_no1より優先度が低い簡潔な理由"
    }
  ]
}

o_no1 と o_no2 に
同じオブジェクトを重複して含めてはいけません。

object には必ず
object_list に記載されている名称をそのまま使用してください。

reason は簡潔にしてください。

JSON以外の説明文、前置き、Markdown、
コードブロックは出力しないでください。
"""


# ============================================================
# 人間の指示
# ============================================================

instruction = input(
    "人間の指示を入力してください："
)


# ============================================================
# GPTへ送るテキスト
# ============================================================

# YAMLの内容を読みやすい形式に変換
object_list_text = yaml.safe_dump(
    object_list,
    allow_unicode=True,
    sort_keys=False
)

user_input = f"""
【人間の指示】

{instruction}


【オブジェクトリスト】

{object_list_text}
"""


# ============================================================
# OpenAI API
# ============================================================

response = client.responses.create(
    model="gpt-5.6-luna",
    reasoning={
        "effort": "medium"
    },
    instructions=system_prompt,
    input=[
        {
            "role": "user",
            "content": [
                {
                    "type": "input_text",
                    "text": user_input
                }
            ]
        }
    ]
)


# ============================================================
# 結果表示
# ============================================================

print()
print("========== GPT ==========")

result_text = response.output_text


# ============================================================
# JSON形式の確認
# ============================================================

try:
    result = json.loads(result_text)

except json.JSONDecodeError as e:

    print(
        "ERROR: GPTの出力が正しいJSON形式ではありません。",
        file=sys.stderr
    )

    print(
        f"JSONDecodeError: {e}",
        file=sys.stderr
    )

    print(
        "\n========== GPTの実際の出力 ==========",
        file=sys.stderr
    )

    print(
        result_text,
        file=sys.stderr
    )

    sys.exit(1)


# ============================================================
# JSONをターミナルに表示
# ============================================================

print(
    json.dumps(
        result,
        ensure_ascii=False,
        indent=2
    )
)


# ============================================================
# JSONファイルとして保存
# ============================================================

OUTPUT_JSON_PATH = (
    Path(__file__).resolve().parent
    / "result_object_prediction.json"
)

with open(
    OUTPUT_JSON_PATH,
    "w",
    encoding="utf-8"
) as f:

    json.dump(
        result,
        f,
        ensure_ascii=False,
        indent=2
    )


print()
print(
    f"JSONファイルを保存しました: {OUTPUT_JSON_PATH}"
)
