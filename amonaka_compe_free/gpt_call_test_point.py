import base64
import json
import sys
import yaml

from pathlib import Path
from openai import OpenAI


# ============================================================
# OpenAI
# ============================================================

client = OpenAI()


# ============================================================
# ファイルパス
# ============================================================

CONFIG_DIR = (
    "/home/carrobo2026/hma2_ws/src/"
    "amonaka_compe_pkg/amonaka_compe_free/config"
)

MAP_INFO_PATH = (
    f"{CONFIG_DIR}/carrobo_move.yaml"
)

CARROBO_HUMAN_PATH = (
    f"{CONFIG_DIR}/carrobo_human.yaml"
)

IMAGE_PATH = (
    f"{CONFIG_DIR}/image.jpeg"
)


# ============================================================
# YAML読み込み
# ============================================================

with open(
    MAP_INFO_PATH,
    "r",
    encoding="utf-8"
) as f:
    map_info = yaml.safe_load(f)


with open(
    CARROBO_HUMAN_PATH,
    "r",
    encoding="utf-8"
) as f:
    carrobo_human = yaml.safe_load(f)


# ============================================================
# カメラ画像読み込み
# ============================================================

with open(IMAGE_PATH, "rb") as f:
    image_bytes = f.read()

image_base64 = base64.b64encode(
    image_bytes
).decode("utf-8")


# ============================================================
# System Prompt
# ============================================================

system_prompt = """
あなたは、家庭内ロボットが次に探索すべき「探索ポイント」を
推定するAIです。

人間から与えられた自然言語の指示、カメラ画像、
マップ情報 map_info、Carrobo と Human の位置・姿勢情報をもとに、
ロボットが対象物を探しに行くべき可能性の高い探索ポイントを
推定してください。

この段階では「何を探すべきか」ではなく、
「どこを探すべきか」だけを判断します。


============================================================
【最重要ルール】
============================================================

候補として出力できる point は、
map_info に存在する探索ポイントだけです。

map_info に存在しないポイント名を
新しく生成してはいけません。

point には、
map_info に記載されているポイント名を
そのまま使用してください。

ポイント名の変更、言い換え、翻訳、省略を
行ってはいけません。

map_info 内のすべてのポイントを
出力する必要はありません。

人間の指示、指差し方向、位置関係との関連性が低いポイントは
候補から除外してください。


============================================================
【この処理で判断するもの】
============================================================

この処理では、

1. 人間の指示に含まれる場所・方向に関する情報
2. カメラ画像から読み取れる Human の指差し方向
3. Human の位置と yaw
4. Carrobo の位置と yaw
5. map_info に登録されている探索ポイントの位置

を利用して、
探索すべきポイントの優先順位を決めてください。

物体そのものの種類を決定することは目的ではありません。


============================================================
【座標系】
============================================================

map_info および carrobo_human に記載されている
x, y は、マップ原点を基準とした絶対座標として扱ってください。

Human や Carrobo を原点にした
独自の座標系へ変換してはいけません。

マップ上の絶対座標を使用して、
各探索ポイントが Human から見て
どの方向に存在するかを判断してください。


============================================================
【yaw と方位】
============================================================

yaw は以下の絶対方位として扱ってください。

- yaw = 0°       → 北
- yaw = +90°     → 東
- yaw = ±180°    → 南
- yaw = -90°     → 西

北方向を Human と Carrobo の位置関係から
独自に定義してはいけません。


============================================================
【カメラ画像と指差し方向】
============================================================

カメラ画像から Human の腕、手、指の向きを確認し、
Human がどの方向を指差しているかを推定してください。

このシステムではカメラ画像について、

- 画像左側 → 東
- 画像右側 → 西

という対応を使用します。

カメラの左右を逆に解釈してはいけません。

必要に応じて Human の yaw も利用し、
指差しがマップ上のどの方位を示しているかを推定してください。


============================================================
【人間の指示から考慮する情報】
============================================================

人間の指示文に場所や方向を示す表現が含まれる場合、
重要な判断材料として使用してください。

例：

- 北
- 北東
- 東
- 西
- 右
- 左
- 前
- 奥
- 手前
- あっち
- そっち
- 指差している方向
- Human の近く
- Carrobo の近く
- 特定の場所名

ただし、
指示文に存在しない条件を根拠なく追加してはいけません。


============================================================
【探索ポイントの評価】
============================================================

map_info 内の各探索ポイントについて、
以下の観点を総合して評価してください。

1. Human の指差し方向との一致度
2. 指示文中の方向・場所表現との一致度
3. Human から見たポイントの方向
4. Human とポイントの位置関係
5. Carrobo からポイントまでの位置関係
6. 他の候補ポイントとの相対的な妥当性

特に Human が明確に指差している場合は、
指差し方向と一致する探索ポイントを強く優先してください。


============================================================
【相対的な比較】
============================================================

各ポイントを単独で評価するだけでなく、
map_info 内の他の探索ポイントと比較してください。

たとえば Human が北東方向を指差しており、

- point A が Human の北東
- point B が Human の北
- point C が Human の南西

にある場合、

point A を最も有力な候補として扱ってください。

point B は、指差し方向に比較的近いなど
合理的な可能性がある場合のみ次点候補にできます。

point C のように方向が大きく異なるポイントは、
特別な根拠がない限り候補から除外してください。


============================================================
【p_no1】
============================================================

p_no1 には、

人間の指示や指差し方向との一致度が高く、
ロボットが優先して探索すべき可能性が高いポイントを
入れてください。

複数のポイントが同程度に有力であれば、
無理に1つへ絞らず複数を含めて構いません。

p_no1 内では、
探索すべき可能性が高いと判断した順番に並べてください。


============================================================
【p_no2】
============================================================

p_no2 には、

p_no1 ほど有力ではないものの、
探索先として合理的な可能性が残っているポイントを
入れてください。

単なる「念のため」という理由だけで
候補を増やしてはいけません。

指示、指差し方向、または位置関係のいずれかに
明確な根拠があるポイントだけを含めてください。

p_no2 内でも、
探索すべき可能性が高い順番に並べてください。


============================================================
【候補を増やしすぎない】
============================================================

探索効率を高めることを重視してください。

map_info に多数のポイントが存在していても、
有力な候補が2個だけなら、
その2個だけを出力してください。

関係の薄いポイントを網羅的に出力してはいけません。


============================================================
【不確実な場合】
============================================================

指示や指差し方向が曖昧で、
複数のポイントが同程度に考えられる場合は、
複数を p_no1 に含めて構いません。

有力候補が存在しない場合は、
p_no1 を空の配列にして構いません。

p_no2 に合理的な候補がない場合は、
p_no2 も空の配列にしてください。

map_info に存在しないポイントを
無理に生成してはいけません。


============================================================
【出力形式】
============================================================

必ず以下の JSON 形式だけで出力してください。

{
  "instruction_features": [
    "指示文・画像・位置情報から抽出した重要な方向または場所の条件"
  ],
  "p_no1": [
    {
      "point": "map_infoに存在するポイント名",
      "reason": "このポイントが有力候補である簡潔な理由"
    }
  ],
  "p_no2": [
    {
      "point": "map_infoに存在するポイント名",
      "reason": "可能性は残るがp_no1より優先度が低い簡潔な理由"
    }
  ]
}

p_no1 と p_no2 に
同じポイントを重複して含めてはいけません。

point には必ず、
map_info に記載されているポイント名を
そのまま使用してください。

reason は簡潔にしてください。

JSON 以外の説明文、前置き、Markdown、
コードブロックは出力しないでください。
"""


# ============================================================
# 人間の指示
# ============================================================

instruction = input(
    "人間の指示を入力してください："
)


# ============================================================
# GPTへ送るテキスト
# ============================================================

map_info_text = yaml.safe_dump(
    map_info,
    allow_unicode=True,
    sort_keys=False
)

carrobo_human_text = yaml.safe_dump(
    carrobo_human,
    allow_unicode=True,
    sort_keys=False
)

user_input = f"""
【人間の指示】

{instruction}


【マップ情報】

{map_info_text}


【CarroboとHumanの位置情報】

{carrobo_human_text}
"""


# ============================================================
# OpenAI API
# ============================================================

response = client.responses.create(
    model="gpt-5.6-luna",
    reasoning={
        "effort": "medium"
    },
    instructions=system_prompt,
    input=[
        {
            "role": "user",
            "content": [
                {
                    "type": "input_text",
                    "text": user_input
                },
                {
                    "type": "input_image",
                    "image_url": (
                        f"data:image/jpeg;base64,"
                        f"{image_base64}"
                    )
                }
            ]
        }
    ]
)


# ============================================================
# 結果取得
# ============================================================

print()
print("========== GPT ==========")

result_text = response.output_text


# ============================================================
# JSON形式の確認
# ============================================================

try:
    result = json.loads(result_text)

except json.JSONDecodeError as e:

    print(
        "ERROR: GPTの出力が正しいJSON形式ではありません。",
        file=sys.stderr
    )

    print(
        f"JSONDecodeError: {e}",
        file=sys.stderr
    )

    print(
        "\n========== GPTの実際の出力 ==========",
        file=sys.stderr
    )

    print(
        result_text,
        file=sys.stderr
    )

    sys.exit(1)


# ============================================================
# JSONをターミナルに表示
# ============================================================

print(
    json.dumps(
        result,
        ensure_ascii=False,
        indent=2
    )
)


# ============================================================
# JSONファイルとして保存
# ============================================================

OUTPUT_JSON_PATH = (
    Path(__file__).resolve().parent
    / "result_point_prediction.json"
)

with open(
    OUTPUT_JSON_PATH,
    "w",
    encoding="utf-8"
) as f:

    json.dump(
        result,
        f,
        ensure_ascii=False,
        indent=2
    )


print()
print(
    f"JSONファイルを保存しました: {OUTPUT_JSON_PATH}"
)
